// 분류기: 키워드 매칭 점수로 상위 토픽 선정. 동점/무매칭 처리 포함.
function classify(text, max = 3) {
  const t = String(text || "");
  const scored = TOPICS.map((topic) => {
    let score = 0;
    for (const k of topic.keywords) if (t.includes(k)) score += k.length >= 3 ? 2 : 1; // 긴 키워드 가중
    return { topic, score };
  }).filter((s) => s.score > 0);
  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, max).map((s) => s.topic);
}

