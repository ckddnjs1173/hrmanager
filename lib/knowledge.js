// 텍스트에서 관련 토픽을 골라 주입용 지식 블록을 만든다(최대 3개).
export function buildKnowledge(text = "") {
  const t = String(text || "");
  const hits = TOPICS.filter((topic) => topic.keywords.some((k) => t.includes(k)));
  const picked = (hits.length ? hits : []).slice(0, 3);
  const blocks = picked.map((p) => p.text);
  // 매칭이 없으면 일반 안내만 주입
  const body = (blocks.length ? blocks.join("\n\n") : GENERIC);
  return (
`\n\n[참고 지식 — 아래 2026년 한국 노무 기준을 답변 근거로 활용하되, 여전히 단정하지 말고 신뢰도 라벨([확정]/[가능성]/[추가 확인 필요])을 붙이고, 사업장 규모·구체적 사실관계 확인을 병행하라. 아래 내용과 사용자 사실관계가 다르면 사용자 사실을 우선하라.]\n${body}`
  );
}

// 여러 메시지를 합쳐 분류용 텍스트 추출(사용자 발화 위주)
export function knowledgeForMessages(messages = []) {
  const userText = messages.filter((m) => m.role === "user").map((m) => m.content).join(" ");
  return buildKnowledge(userText);
}
