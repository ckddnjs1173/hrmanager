export function buildKnowledge(text = "") {
  const picked = classify(text);
  const blocks = picked.length ? picked.map((p) => p.text) : [GENERIC];
  // 매칭이 1개뿐이어도 일반 기준을 살짝 덧대 맥락 보강
  if (picked.length === 1) blocks.push(GENERIC);
  return (
`\n\n[참고 지식 — 아래 2026년 한국 노무 기준을 답변 근거로 활용하라. 단, 이 내용을 그대로 나열하지 말고 사용자 사안에 맞게 자연스럽게 녹여라. 여전히 단정하지 말고 신뢰도 라벨([확정]/[가능성]/[추가 확인 필요])을 붙이고, 사업장 규모·구체 사실관계 확인을 병행하라. 아래와 사용자 사실이 다르면 사용자 사실을 우선하라. 수치·상한은 매년 바뀌므로 '2026년 기준'임을 밝혀라.]
${blocks.join("\n\n")}

${FOOTER}`
  );
}

// 여러 메시지를 합쳐 분류(사용자 발화 위주, 최근 발화에 가중치).
export function knowledgeForMessages(messages = []) {
  const users = messages.filter((m) => m.role === "user").map((m) => m.content);
  // 최근 발화를 두 번 넣어 가중(최근 주제 우선 분류)
  const text = (users.slice(-1)[0] || "") + " " + users.join(" ");
  return buildKnowledge(text);
}

